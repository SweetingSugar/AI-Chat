create table if not exists tool_mcp_server (
    id bigint not null auto_increment primary key comment 'MCP 服务主键 ID',
    server_code varchar(100) not null comment 'MCP 服务唯一编码',
    server_name varchar(100) not null comment 'MCP 服务名称',
    endpoint_url varchar(500) not null comment 'MCP 服务端点 URL',
    auth_type varchar(32) not null default 'NONE' comment '认证类型：NONE 无认证，BEARER Bearer Token，API_KEY API 密钥',
    auth_header_name varchar(100) null comment '认证请求头名称，API_KEY 类型使用',
    credential_ciphertext varchar(4096) null comment '加密后的认证凭据',
    credential_version int not null default 1 comment '认证凭据版本',
    secret_headers_ciphertext text null comment '加密后的敏感请求头',
    connect_timeout int not null default 10 comment '连接超时时间，单位：秒',
    read_timeout int not null default 60 comment '读取超时时间，单位：秒',
    status tinyint not null default 1 comment '启用状态：0 禁用，1 启用',
    deleted tinyint not null default 0 comment '逻辑删除标记：0 未删除，1 已删除',
    last_discovery_time datetime null comment '最后一次工具发现时间',
    last_discovery_status varchar(32) null comment '最后一次工具发现状态：SUCCESS 成功，FAILED 失败',
    last_discovery_error varchar(1000) null comment '最后一次工具发现错误信息',
    create_time datetime not null default current_timestamp comment '创建时间',
    update_time datetime not null default current_timestamp on update current_timestamp comment '更新时间',
    unique key uk_tool_mcp_server_code (server_code),
    key idx_tool_mcp_server_status (status, deleted)
) comment = 'MCP 服务配置表';

create table if not exists tool_definition (
    id bigint not null auto_increment primary key comment '工具定义主键 ID',
    tool_code varchar(100) not null comment '工具唯一编码',
    tool_name varchar(100) not null comment '工具名称',
    description varchar(1000) null comment '工具描述',
    tool_type varchar(32) not null comment '工具类型：HTTP HTTP 工具，MCP MCP 工具',
    source varchar(32) not null comment '工具来源：MANUAL 手动配置，DISCOVERED 自动发现',
    status tinyint not null default 0 comment '启用状态：0 禁用，1 启用',
    availability varchar(32) not null default 'AVAILABLE' comment '可用性：AVAILABLE 可用，STALE 信息已过期',
    mcp_server_id bigint null comment '关联的 MCP 服务 ID',
    remote_tool_name varchar(200) null comment 'MCP 服务端暴露的远程工具名称',
    http_config json null comment 'HTTP 工具配置 JSON',
    auth_type varchar(32) not null default 'NONE' comment '认证类型：NONE 无认证，BEARER Bearer Token，API_KEY API 密钥',
    auth_header_name varchar(100) null comment '认证请求头名称，API_KEY 类型使用',
    credential_ciphertext varchar(4096) null comment '加密后的认证凭据',
    credential_version int not null default 1 comment '认证凭据版本',
    secret_headers_ciphertext text null comment '加密后的敏感请求头',
    input_schema json null comment '工具输入参数 JSON Schema',
    deleted tinyint not null default 0 comment '逻辑删除标记：0 未删除，1 已删除',
    create_time datetime not null default current_timestamp comment '创建时间',
    update_time datetime not null default current_timestamp on update current_timestamp comment '更新时间',
    unique key uk_tool_definition_code (tool_code),
    unique key uk_tool_definition_mcp_remote (mcp_server_id, remote_tool_name),
    key idx_tool_definition_status (tool_type, status, availability, deleted),
    key idx_tool_definition_server (mcp_server_id, deleted)
) comment = '工具定义表';

create table if not exists tool_invocation_log (
    id bigint not null auto_increment primary key comment '工具调用日志主键 ID',
    request_id varchar(64) not null comment '请求唯一 ID',
    tool_id bigint null comment '工具定义 ID',
    tool_code varchar(100) not null comment '调用时的工具编码',
    user_id bigint null comment '调用用户 ID',
    tool_type varchar(32) not null comment '工具类型：HTTP HTTP 工具，MCP MCP 工具',
    status varchar(32) not null comment '调用状态：RUNNING 运行中，SUCCESS 成功，FAILED 失败',
    duration_ms bigint null comment '调用耗时，单位：毫秒',
    error_code varchar(100) null comment '错误编码',
    error_message varchar(1000) null comment '错误信息',
    start_time datetime not null comment '调用开始时间',
    end_time datetime null comment '调用结束时间',
    create_time datetime not null default current_timestamp comment '创建时间',
    key idx_tool_invocation_request (request_id),
    key idx_tool_invocation_tool_time (tool_id, start_time),
    key idx_tool_invocation_user_time (user_id, start_time),
    key idx_tool_invocation_status_time (status, start_time)
) comment = '工具调用日志表';
