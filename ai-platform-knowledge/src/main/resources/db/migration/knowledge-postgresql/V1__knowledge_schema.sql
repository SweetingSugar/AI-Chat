create extension if not exists vector;

create table if not exists knowledge_base (
    id bigint generated by default as identity primary key,
    user_id bigint not null,
    name varchar(100) not null,
    description varchar(1000),
    embedding_model_id bigint not null,
    embedding_model_version int not null default 1,
    pending_embedding_model_id bigint,
    pending_embedding_model_version int,
    pending_index_version bigint,
    active_index_version bigint not null default 1,
    status varchar(32) not null default 'ACTIVE',
    deleted boolean not null default false,
    create_time timestamp not null default current_timestamp,
    update_time timestamp not null default current_timestamp
);

create unique index if not exists uk_knowledge_base_user_name
    on knowledge_base (user_id, name) where deleted = false;
create index if not exists idx_knowledge_base_user_status
    on knowledge_base (user_id, status, deleted, update_time);

create table if not exists knowledge_document (
    id bigint generated by default as identity primary key,
    knowledge_base_id bigint not null references knowledge_base(id),
    source_type varchar(32) not null,
    file_id bigint,
    title varchar(255) not null,
    raw_content text,
    content_hash varchar(64),
    status varchar(32) not null default 'PENDING',
    index_version bigint not null default 1,
    active_index_version bigint,
    chunk_count int not null default 0,
    error_code varchar(64),
    error_message varchar(1000),
    deleted boolean not null default false,
    create_time timestamp not null default current_timestamp,
    update_time timestamp not null default current_timestamp
);

create unique index if not exists uk_knowledge_document_file
    on knowledge_document (knowledge_base_id, file_id)
    where file_id is not null and deleted = false;
create index if not exists idx_knowledge_document_base_status
    on knowledge_document (knowledge_base_id, status, deleted, update_time);

create table if not exists knowledge_chunk (
    id bigint generated by default as identity primary key,
    document_id bigint not null references knowledge_document(id),
    index_version bigint not null,
    chunk_index int not null,
    content text not null,
    estimated_tokens int not null,
    chunk_metadata jsonb not null default '{}'::jsonb,
    create_time timestamp not null default current_timestamp
);

create unique index if not exists uk_knowledge_chunk_order
    on knowledge_chunk (document_id, index_version, chunk_index);

create table if not exists knowledge_chunk_embedding (
    id bigint generated by default as identity primary key,
    chunk_id bigint not null references knowledge_chunk(id),
    knowledge_base_id bigint not null references knowledge_base(id),
    embedding_model_id bigint not null,
    model_version int not null,
    dimension int not null,
    index_version bigint not null,
    embedding vector not null,
    create_time timestamp not null default current_timestamp
);

create unique index if not exists uk_knowledge_embedding_version
    on knowledge_chunk_embedding (chunk_id, index_version);
create index if not exists idx_knowledge_embedding_search
    on knowledge_chunk_embedding (knowledge_base_id, embedding_model_id, dimension, index_version);

create table if not exists knowledge_index_task (
    id bigint generated by default as identity primary key,
    knowledge_base_id bigint not null references knowledge_base(id),
    document_id bigint not null references knowledge_document(id),
    embedding_model_id bigint not null,
    model_version int not null,
    index_version bigint not null,
    status varchar(32) not null default 'PENDING',
    attempt_count int not null default 0,
    max_attempts int not null default 3,
    next_retry_at timestamp not null default current_timestamp,
    locked_at timestamp,
    started_at timestamp,
    completed_at timestamp,
    error_code varchar(64),
    error_message varchar(1000),
    create_time timestamp not null default current_timestamp,
    update_time timestamp not null default current_timestamp
);

create unique index if not exists uk_knowledge_task_document_version
    on knowledge_index_task (document_id, index_version);
create index if not exists idx_knowledge_task_claim
    on knowledge_index_task (status, next_retry_at, id);

