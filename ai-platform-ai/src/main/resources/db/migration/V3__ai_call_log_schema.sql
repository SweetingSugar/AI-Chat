create table if not exists ai_call_log (
    id bigint not null auto_increment primary key,
    request_id varchar(64) not null,
    user_id bigint null,
    session_id bigint null,
    message_id bigint null,
    provider_id bigint not null,
    model_id bigint not null,
    provider_name varchar(100) null,
    model_code varchar(100) null,
    input_tokens int null,
    output_tokens int null,
    total_tokens int null,
    usage_source varchar(32) null,
    duration_ms bigint null,
    call_type varchar(32) not null,
    status varchar(32) not null,
    finish_reason varchar(100) null,
    error_code varchar(100) null,
    error_message varchar(1000) null,
    start_time datetime not null,
    end_time datetime null,
    create_time datetime not null default current_timestamp,
    key idx_ai_call_log_request_id (request_id),
    key idx_ai_call_log_user_time (user_id, start_time),
    key idx_ai_call_log_model_time (model_id, start_time)
);
